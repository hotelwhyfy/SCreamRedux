#!/usr/bin/env python3
"""Catalogue how decompiled SCream scripts call the engine's sc* API.

For each function: call count, observed arities, the SC_* constants seen in each
argument position, and a few example calls. Output is Markdown.

Usage:
    api_usage.py SCRIPT.lua [SCRIPT.lua...] > api.md
"""

import collections
import re
import sys

CALL = re.compile(r"\b(sc[A-Z]\w*)\(")


def split_args(s, start):
    """Parse a balanced argument list beginning just after '('. Returns (args, end)."""
    args, depth, cur, i, quote = [], 0, [], start, None
    while i < len(s):
        c = s[i]
        if quote:
            cur.append(c)
            if c == "\\":
                cur.append(s[i + 1])
                i += 1
            elif c == quote:
                quote = None
        elif c in "\"'":
            quote = c
            cur.append(c)
        elif c in "([{":
            depth += 1
            cur.append(c)
        elif c in ")]}":
            if depth == 0:
                a = "".join(cur).strip()
                if a or args:
                    args.append(a)
                return args, i
            depth -= 1
            cur.append(c)
        elif c == "," and depth == 0:
            args.append("".join(cur).strip())
            cur = []
        else:
            cur.append(c)
        i += 1
    return args, i


def classify(arg):
    if re.fullmatch(r"SC_\w+", arg):
        return arg
    if arg.startswith(('"', "'")):
        return "<str>"
    if re.fullmatch(r"-?\d+(\.\d+)?", arg):
        return "<num>"
    if re.fullmatch(r"(dlg|msg)\w+", arg):
        return "<text>"
    return "<expr>"


def main():
    calls = collections.Counter()
    arity = collections.defaultdict(collections.Counter)
    slots = collections.defaultdict(lambda: collections.defaultdict(collections.Counter))
    examples = collections.defaultdict(list)
    for path in sys.argv[1:]:
        with open(path, encoding="latin-1") as f:
            src = f.read()
        for m in CALL.finditer(src):
            name = m.group(1)
            args, end = split_args(src, m.end())
            calls[name] += 1
            arity[name][len(args)] += 1
            for i, a in enumerate(args):
                slots[name][i][classify(a)] += 1
            text = src[m.start():end + 1]
            if len(examples[name]) < 3 and text not in examples[name] and len(text) < 160:
                examples[name].append(text)

    print("# sc* API usage\n")
    print(f"Generated by `tools/api_usage.py` from: {', '.join(sys.argv[1:])}\n")
    print("| Function | Calls | Arities |\n|---|---:|---|")
    for name, n in calls.most_common():
        ar = ", ".join(str(k) for k in sorted(arity[name]))
        print(f"| `{name}` | {n} | {ar} |")
    print()
    for name in sorted(calls):
        print(f"## `{name}` ({calls[name]} calls)\n")
        for i in sorted(slots[name]):
            kinds = ", ".join(f"{k}×{v}" for k, v in slots[name][i].most_common(12))
            print(f"- arg {i + 1}: {kinds}")
        print()
        for e in examples[name]:
            print(f"    {e}")
        print()


if __name__ == "__main__":
    main()
